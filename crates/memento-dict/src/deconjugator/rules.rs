//! Static Japanese deconjugation rule tables with Yomitan short-causative sub-conditions.

use super::WordForm::{self, *};

// Yomitan sub-conditions for Godan `-す` vs short causative (`-あす` vs `-さす`):
// - SUB_V5_D: dictionary godan verb
// - SUB_V5_SP: non-`さす` short causative (`書かす`, `読ます`, ...) — allows Passive (`書かされる`)
// - SUB_V5_SS: `さす` short causative (`食べさす`, `話さす`, `来さす`, `さす`) — blocks Passive (`*食べされる`, `*話さされる`, `*される`)
pub(super) const SUB_NONE: u8 = 0;
pub(super) const SUB_V5_D: u8 = 1 << 0;
pub(super) const SUB_V5_SP: u8 = 1 << 1;
pub(super) const SUB_V5_SS: u8 = 1 << 2;
pub(super) const SUB_V5_ALL: u8 = SUB_V5_D | SUB_V5_SP | SUB_V5_SS;
pub(super) const SUB_CAUS_LONG: u8 = 1 << 3;

pub(super) struct Rule {
    pub base: &'static str,
    pub conjugated: &'static str,
    pub base_type: WordForm,
    pub conjugated_type: WordForm,
    /// Sub-conditions produced when `base_type == GodanVerb` (for silent short-causative chaining).
    pub v5_out: u8,
    /// Required sub-condition mask when `conjugated_type == Causative`.
    pub caus_req: u8,
}

impl Rule {
    const fn new(
        base: &'static str,
        conjugated: &'static str,
        base_type: WordForm,
        conjugated_type: WordForm,
    ) -> Self {
        let v5_out = if matches!(base_type, GodanVerb) {
            match conjugated_type {
                // Passive `す <- される` allows dictionary v5 and non-`さす` short causative (`書かされる`),
                // NEVER `さす` short causative (`*食べされる`, `*話さされる`, `*勉強される` as causative).
                Passive => SUB_V5_D | SUB_V5_SP,
                // Potential `す <- せる` and Causative `す <- させる` apply only to dictionary v5,
                // never to short causatives (`食べさせる` / `書かせる` are plain causatives, not potentials).
                Potential | Causative => SUB_V5_D,
                _ => SUB_V5_ALL,
            }
        } else {
            SUB_NONE
        };
        let caus_req = if matches!(conjugated_type, Causative) {
            SUB_CAUS_LONG
        } else {
            SUB_NONE
        };
        Self {
            base,
            conjugated,
            base_type,
            conjugated_type,
            v5_out,
            caus_req,
        }
    }

    const fn short_causative(
        base: &'static str,
        conjugated: &'static str,
        base_type: WordForm,
        caus_req: u8,
    ) -> Self {
        Self {
            base,
            conjugated,
            base_type,
            conjugated_type: Causative,
            v5_out: SUB_V5_D,
            caus_req,
        }
    }
}

pub(super) struct SilentRule {
    pub base: &'static str,
    pub base_type: WordForm,
    pub conjugated_type: WordForm,
    /// For `conjugated_type == GodanVerb`, requires overlap with the parent rule's `v5_out`.
    pub required_v5_sub: u8,
    /// Passed to `deconjugate_recursive` when `base_type == Causative`.
    pub caus_sub: u8,
}

impl SilentRule {
    const fn new(base: &'static str, base_type: WordForm, conjugated_type: WordForm) -> Self {
        let caus_sub = if matches!(base_type, Causative) {
            SUB_CAUS_LONG
        } else {
            SUB_NONE
        };
        let required_v5_sub = if matches!(conjugated_type, GodanVerb) {
            SUB_V5_D
        } else {
            SUB_NONE
        };
        Self {
            base,
            base_type,
            conjugated_type,
            required_v5_sub,
            caus_sub,
        }
    }

    const fn short_causative_v5(base: &'static str, sub: u8) -> Self {
        Self {
            base,
            base_type: Causative,
            conjugated_type: GodanVerb,
            required_v5_sub: sub,
            caus_sub: sub,
        }
    }
}

