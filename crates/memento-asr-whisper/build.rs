//! Build script for the `memento-asr-whisper` crate.
//!
//! The crate binds the whisper.cpp C API built by the CMake tree
//! (`extern/CMakeLists.txt`, FetchContent tag v1.9.4). Two binding sources:
//!
//! 1. **Regenerated (authoritative)**: when `WHISPER_INCLUDE_DIR` is set —
//!    which `src/asr/rust_whisper.cmake` does through
//!    `corrosion_set_env_vars` for every CMake build — bindgen runs against
//!    the *actually fetched* `whisper.h` (`GGML_INCLUDE_DIR`, optional,
//!    defaults to `<include>/../ggml/include` for the whisper.cpp layout).
//!    Generated bindings are written to `$OUT_DIR/whisper_bindings.rs`.
//!    If the variable is set but bindgen cannot run, the build FAILS: the
//!    CMake gate must never silently bind against a stale header.
//!
//! 2. **Checked-in fallback**: for standalone `cargo build`/`cargo test`
//!    (no CMake environment), `src/whisper_bindings_pregenerated.rs` —
//!    byte-identical to the bindgen output for the v1.9.4 header — is copied
//!    to `$OUT_DIR` instead. Regenerate it by running a CMake build with
//!    `MEMENTO_ASR_WHISPER_RUST=ON` and copying the generated file:
//!
//!    ```text
//!    find build-rust-whisper -name whisper_bindings.rs -path '*out*'
//!    cp <that file> rust/memento-asr-whisper/src/whisper_bindings_pregenerated.rs
//!    ```
//!
//! Layout drift between the binding and the compiled library is caught at
//! test time by the defaults-parity section of
//! `tests/mpv-memory-subtitles/whisper_engine_equal_test.cpp`, which compares
//! every `whisper_full_params` / `whisper_context_params` field and the
//! struct sizes as dumped by C++ and by Rust.

use std::path::{Path, PathBuf};

/// Banner prepended to generated bindings; the checked-in fallback carries
/// the identical text (regenerated output must match byte-for-byte).
const BANNER: &str = "/* Generated by bindgen 0.73 for the whisper.cpp v1.9.4 C API.\n * DO NOT EDIT BY HAND. Regenerated by build.rs against the actually fetched\n * whisper.h whenever WHISPER_INCLUDE_DIR is set; the file\n * src/whisper_bindings_pregenerated.rs is the byte-identical checked-in\n * fallback used when that variable is absent (standalone cargo builds).\n */";

const FALLBACK_RELATIVE_PATH: &str = "src/whisper_bindings_pregenerated.rs";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={FALLBACK_RELATIVE_PATH}");
    println!("cargo:rerun-if-env-changed=WHISPER_INCLUDE_DIR");
    println!("cargo:rerun-if-env-changed=GGML_INCLUDE_DIR");

    let manifest_dir = PathBuf::from(env_var("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env_var("OUT_DIR"));
    let dest = out_dir.join("whisper_bindings.rs");

    let explicit_include = std::env::var_os("WHISPER_INCLUDE_DIR").map(PathBuf::from);
    let include_dir =
        explicit_include.clone().or_else(|| discover_include_dir(&manifest_dir));

    if let Some(include_dir) = include_dir.filter(|dir| dir.join("whisper.h").is_file()) {
        println!("cargo:rerun-if-changed={}", include_dir.join("whisper.h").display());
        let ggml_dir = std::env::var_os("GGML_INCLUDE_DIR")
            .map(PathBuf::from)
            .unwrap_or_else(|| {
                include_dir
                    .parent()
                    .map(|parent| parent.join("ggml").join("include"))
                    .unwrap_or_else(|| PathBuf::from("ggml/include"))
            });
        println!("cargo:rerun-if-changed={}", ggml_dir.join("ggml.h").display());

        // bindgen panics (rather than returning an error) when libclang is
        // unavailable; treat that as "generation unavailable".
        let generated = std::panic::catch_unwind(|| generate(&include_dir, &ggml_dir));
        match generated {
            Ok(Ok(code)) => {
                std::fs::write(&dest, code)
                    .unwrap_or_else(|err| panic!("memento-asr-whisper: cannot write {dest:?}: {err}"));
                return;
            }
            Ok(Err(err)) => {
                if explicit_include.is_some() {
                    panic!(
                        "memento-asr-whisper: bindgen failed against WHISPER_INCLUDE_DIR={}: {err}",
                        include_dir.display()
                    );
                }
                println!(
                    "cargo:warning=memento-asr-whisper: bindgen unavailable ({err}); \
                     using checked-in bindings"
                );
            }
            Err(_) => {
                if explicit_include.is_some() {
                    panic!(
                        "memento-asr-whisper: bindgen panicked for WHISPER_INCLUDE_DIR={} \
                         (libclang missing?); refusing to fall back in a CMake build",
                        include_dir.display()
                    );
                }
                println!(
                    "cargo:warning=memento-asr-whisper: bindgen panicked (libclang missing?); \
                     using checked-in bindings"
                );
            }
        }
    } else if explicit_include.is_some() {
        panic!(
            "memento-asr-whisper: WHISPER_INCLUDE_DIR={} does not contain whisper.h",
            explicit_include.expect("checked above").display()
        );
    } else {
        println!(
            "cargo:warning=memento-asr-whisper: no whisper.cpp header found (WHISPER_INCLUDE_DIR \
             unset and no local build tree); using checked-in bindings generated for v1.9.4"
        );
    }

    let fallback = manifest_dir.join(FALLBACK_RELATIVE_PATH);
    std::fs::copy(&fallback, &dest).unwrap_or_else(|err| {
        panic!(
            "memento-asr-whisper: cannot copy fallback bindings {fallback:?} -> {dest:?}: {err}"
        )
    });
}

/// Standalone-cargo discovery: look for the header in the known local build
/// trees (`<repo>/build*/_deps/whispercpp-src/include`). The CMake path always
/// passes `WHISPER_INCLUDE_DIR` explicitly, so this is a developer
/// convenience for `cargo test` in `rust/`.
fn discover_include_dir(manifest_dir: &Path) -> Option<PathBuf> {
    let rust_dir = manifest_dir.parent()?;
    let repo_dir = rust_dir.parent()?;
    let mut candidates: Vec<PathBuf> = Vec::new();
    if let Ok(entries) = std::fs::read_dir(repo_dir) {
        for entry in entries.flatten() {
            let name = entry.file_name();
            if name.to_string_lossy().starts_with("build") {
                candidates.push(
                    entry
                        .path()
                        .join("_deps")
                        .join("whispercpp-src")
                        .join("include"),
                );
            }
        }
    }
    candidates.sort();
    candidates
        .into_iter()
        .find(|candidate| candidate.join("whisper.h").is_file())
}

/// Run bindgen with the exact configuration the checked-in fallback was
/// generated with (see the module docs).
fn generate(include_dir: &Path, ggml_include_dir: &Path) -> Result<String, String> {
    let header = include_dir.join("whisper.h");
    let bindings = bindgen::Builder::default()
        .header(header.to_string_lossy())
        .clang_arg(format!("-I{}", include_dir.display()))
        .clang_arg(format!("-I{}", ggml_include_dir.display()))
        .allowlist_function("whisper_.*")
        .allowlist_type("whisper_.*")
        .allowlist_type("ggml_abort_callback")
        .allowlist_var("WHISPER_.*")
        .derive_default(true)
        .derive_debug(true)
        .derive_copy(true)
        .layout_tests(true)
        .raw_line(BANNER)
        .generate()
        .map_err(|err| err.to_string())?;

    let mut code: Vec<u8> = Vec::new();
    bindings
        .write(Box::new(&mut code))
        .map_err(|err| err.to_string())?;
    String::from_utf8(code).map_err(|err| err.to_string())
}

/// Read a build-script environment variable that is always set by cargo.
fn env_var(name: &str) -> String {
    std::env::var(name).unwrap_or_else(|_| panic!("memento-asr-whisper: {name} is not set"))
}
