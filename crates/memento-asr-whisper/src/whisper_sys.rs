//! Raw bindgen bindings to the whisper.cpp C API.
//!
//! Generated by `build.rs` against the actually fetched
//! `_deps/whispercpp-src/include/whisper.h` (FetchContent tag v1.9.4) when
//! the CMake build provides `WHISPER_INCLUDE_DIR`; otherwise the checked-in
//! `src/whisper_bindings_pregenerated.rs` (generated from the same header
//! revision) is used. Layout drift is detected by the defaults-parity
//! assertions in `tests/mpv-memory-subtitles/whisper_engine_equal_test.cpp`.
//!
//! Never hand-edit the generated files: bump the FetchContent tag, rebuild
//! with `MEMENTO_ASR_WHISPER_RUST=ON`, and copy the regenerated bindings over
//! the checked-in fallback (see `build.rs`).

// The bindgen output follows C naming conventions.
#![allow(
    non_upper_case_globals,
    non_camel_case_types,
    non_snake_case,
    dead_code,
    improper_ctypes_definitions,
    clippy::all
)]

include!(concat!(env!("OUT_DIR"), "/whisper_bindings.rs"));
